// app/layout.tsx
import type { Metadata } from "next";
import localFont from "next/font/local";
import "@/app/globals.css";
import { auth } from "@/auth";
import { SessionProvider } from "next-auth/react";
import dynamic from "next/dynamic";
import ClientNavbarControl from "@/components/navbar/ClientNavbarControl";
import Footer from "@/components/footer";

const geistSans = localFont({
  src: "./fonts/GeistVF.woff",
  variable: "--font-geist-sans",
  weight: "100 900",
});
const geistMono = localFont({
  src: "./fonts/GeistMonoVF.woff",
  variable: "--font-geist-mono",
  weight: "100 900",
});

export const metadata: Metadata = {
  title: "Account Saver",
  description: "Generated by create next app",
};

const DynamicNavbar = dynamic(() => import("@/components/navbar"), {
  ssr: false,
});

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const session = await auth();

  return (
    <html lang="en">
      <body
        className={`${geistSans.variable} ${geistMono.variable} scroll-smooth bg-slate-800`}
      >
        <SessionProvider session={session}>
          <ClientNavbarControl>
            <DynamicNavbar session={session} />
          </ClientNavbarControl>

          {/* Suspense untuk seluruh main layout */}
          {/* <Suspense fallback={<Loading />}> */}
          <main>{children}</main>
          <Footer />
          {/* </Suspense> */}
        </SessionProvider>
      </body>
    </html>
  );
}
